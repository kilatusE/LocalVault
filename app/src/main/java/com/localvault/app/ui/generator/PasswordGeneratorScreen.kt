import com.localvault.app.ui.theme.VaultTheme

@Composable
fun PasswordGeneratorScreen(
    options: PasswordGenOptions,
    onOptionsChange: (PasswordGenOptions) -> Unit,
    clipboardClearSeconds: Int
) {
    val colors = VaultTheme.colors
    val context = LocalContext.current

    var optionsExpanded by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(PasswordGenerator.generate(options)) }

    // 別画面（新規登録など）で条件が変わった場合も反映
    LaunchedEffect(options) {
        generated = PasswordGenerator.generate(options)
    }

    val score = remember(generated) { PasswordGenerator.calculateStrengthScore(generated) }
    val strength = remember(generated) { PasswordGenerator.evaluateStrength(generated) }
    val strengthColor = colors.colorForStrength(strength)

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(colors.bg)
            .statusBarsPadding()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 20.dp)
    ) {
        Spacer(Modifier.height(18.dp))

        Text(
            text = "パスワード作成",
            color = colors.textPrimary,
            fontSize = 26.sp,
            fontWeight = FontWeight.Bold
        )
        Spacer(Modifier.height(4.dp))
        Text(
            text = "推測されにくい安全なパスワードを自動で作成します",
            color = colors.textSecondary,
            fontSize = 12.sp,
            lineHeight = 18.sp
        )

        Spacer(Modifier.height(18.dp))

        // 条件入力を上部に配置（タップで開閉）
        PasswordGenOptionsCard(
            options = options,
            expanded = optionsExpanded,
            onToggleExpanded = { optionsExpanded = !optionsExpanded },
            onOptionsChange = { newOpts ->
                onOptionsChange(newOpts)
                generated = PasswordGenerator.generate(newOpts)
            }
        )

        Spacer(Modifier.height(16.dp))

        // 生成結果カード
        Card(
            modifier = Modifier.fillMaxWidth(),
            shape = RoundedCornerShape(18.dp),
            colors = CardDefaults.cardColors(containerColor = colors.card),
            border = BorderStroke(1.dp, colors.border)
        ) {
            Column(modifier = Modifier.padding(20.dp)) {
                Text(
                    text = generated,
                    color = colors.textPrimary,
                    fontSize = 20.sp,
                    fontFamily = FontFamily.Monospace,
                    fontWeight = FontWeight.SemiBold,
                    lineHeight = 26.sp
                )
                Spacer(Modifier.height(16.dp))
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text(
                        text = "強さ: ${strength.label}",
                        color = strengthColor,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Medium
                    )
                    Text("${generated.length} 文字", color = colors.textSecondary, fontSize = 12.sp)
                }
                Spacer(Modifier.height(6.dp))
                LinearProgressIndicator(
                    progress = { score / 100f },
                    color = strengthColor,
                    trackColor = colors.surfaceElevated,
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(6.dp)
                        .clip(RoundedCornerShape(3.dp))
                )
                Spacer(Modifier.height(20.dp))
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    OutlinedButton(
                        onClick = { generated = PasswordGenerator.generate(options) },
                        border = BorderStroke(1.dp, colors.borderStrong),
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier
                            .weight(1f)
                            .height(48.dp)
                    ) {
                        Icon(Icons.Rounded.Refresh, contentDescription = null, tint = colors.textPrimary)
                        Spacer(Modifier.width(6.dp))
                        Text("作り直す", color = colors.textPrimary)
                    }
                    Button(
                        onClick = {
                            ClipboardHelper.copySensitive(
                                context, "generated_password", generated, clipboardClearSeconds
                            )
                            Toast.makeText(
                                context,
                                "コピーしました（${clipboardClearSeconds}秒後に自動消去）",
                                Toast.LENGTH_SHORT
                            ).show()
                        },
                        colors = ButtonDefaults.buttonColors(
                            containerColor = colors.primaryButtonBg,
                            contentColor = colors.primaryButtonFg
                        ),
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier
                            .weight(1f)
                            .height(48.dp)
                    ) {
                        Icon(Icons.Rounded.ContentCopy, contentDescription = null)
                        Spacer(Modifier.width(6.dp))
                        Text("コピー", fontWeight = FontWeight.SemiBold)
                    }
                }
            }
        }

        Spacer(Modifier.height(28.dp))
    }
}
